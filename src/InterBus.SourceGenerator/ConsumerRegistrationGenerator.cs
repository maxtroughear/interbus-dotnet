using System.Collections.Generic;
using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace InterBus.SourceGenerator;

[Generator]
public sealed class ConsumerRegistrationGenerator : IIncrementalGenerator
{
    private const string ConsumerInterfaceMetadataName = "InterBus.IConsumer`1";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var classSymbols = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (node, _) => node is ClassDeclarationSyntax,
                transform: static (ctx, ct) =>
                    ctx.SemanticModel.GetDeclaredSymbol(ctx.Node, ct) as INamedTypeSymbol)
            .Where(static symbol => symbol is not null)
            .Select(static (symbol, _) => symbol!);
        
        var combined = classSymbols.Collect().Combine(context.CompilationProvider);
        
        context.RegisterSourceOutput(combined, static (ctx, data) =>
            Execute(ctx, data.Left, data.Right));
    }

    private static void Execute(
        SourceProductionContext ctx,
        ImmutableArray<INamedTypeSymbol> classSymbols,
        Compilation compilation)
    {
        var consumerInterfaceSymbol = compilation.GetTypeByMetadataName(ConsumerInterfaceMetadataName);
        if (consumerInterfaceSymbol is null) return;
        
        // Group message types by consumer: one entry per consumer class with all handled message types.
        var byConsumer = new List<(INamedTypeSymbol Consumer, List<INamedTypeSymbol> Messages)>();

        foreach (var classSymbol in classSymbols)
        {
            if (classSymbol.IsAbstract || classSymbol.TypeKind != TypeKind.Class) continue;

            List<INamedTypeSymbol>? messages = null;

            foreach (var iface in classSymbol.AllInterfaces)
            {
                if (iface.TypeArguments.Length != 1) continue;

                if (!SymbolEqualityComparer.Default.Equals(
                        iface.OriginalDefinition, consumerInterfaceSymbol)) continue;

                if (iface.TypeArguments[0] is not INamedTypeSymbol messageType) continue;

                messages ??= new List<INamedTypeSymbol>();
                messages.Add(messageType);
            }

            if (messages is not null)
                byConsumer.Add((classSymbol, messages));
        }

        if (byConsumer.Count == 0) return;
        
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace InterBus.Generated");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// Source-generated consumer registrations.");
        sb.AppendLine("    /// Produced by <c>InterBus.SourceGenerator</c> at compile time -");
        sb.AppendLine("    /// no runtime reflection is required.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    internal static class InterBusConsumerRegistrations");
        sb.AppendLine("    {");
        sb.AppendLine("        /// <summary>");
        sb.AppendLine("        /// Register all <c>IConsumer&lt;T&gt;</c> implementations");
        sb.AppendLine("        /// discovered in this assembly at compile time.");
        sb.AppendLine("        /// Each consumer class is registered once, regardless of how many");
        sb.AppendLine("        /// message types it handles.");
        sb.AppendLine("        /// </summary>");
        sb.AppendLine("        public static global::InterBus.IInterBusBuilder AddGeneratedConsumers(");
        sb.AppendLine("            this global::InterBus.IInterBusBuilder builder)");
        sb.AppendLine("        {");

        foreach (var (consumer, messages) in byConsumer)
        {
            var consumerFqn = consumer.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

            foreach (var message in messages)
            {
                var messageFqn = message.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                sb.AppendLine(
                    $"            builder.AddConsumer<{consumerFqn}, {messageFqn}>();");
            }
        }

        sb.AppendLine("            return builder;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        ctx.AddSource(
            "InterBusConsumerRegistrations.g.cs",
            SourceText.From(sb.ToString(), Encoding.UTF8));
    }
}

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Xunit;

namespace InterBus.SourceGenerator.Tests;

/// <summary>
/// Unit tests for <see cref="ConsumerRegistrationGenerator"/>.
///
/// Each test creates a minimal in-memory <see cref="CSharpCompilation"/> that references the real
/// <c>InterBus</c> assembly, runs the generator against it, and asserts on the generated source text.
/// This exercises the generator without requiring an end-to-end build of a real project.
/// </summary>
public sealed class ConsumerRegistrationGeneratorTests
{
    // -------------------------------------------------------------------------
    // Basic discovery
    // -------------------------------------------------------------------------

    [Fact]
    public void Generator_SingleConsumer_GeneratesAddGeneratedConsumers()
    {
        const string source = """
            using System.Threading;
            using System.Threading.Tasks;
            using InterBus;

            namespace MyApp
            {
                public record OrderPlaced(System.Guid OrderId);

                public sealed class OrderPlacedConsumer : IConsumer<OrderPlaced>
                {
                    public Task Consume(OrderPlaced message, CancellationToken cancellationToken = default)
                        => Task.CompletedTask;
                }
            }
            """;

        var result = RunGenerator(source);

        Assert.Empty(result.Diagnostics);
        Assert.Single(result.GeneratedTrees);

        var generated = result.GeneratedTrees[0].ToString();
        Assert.Contains("// <auto-generated/>", generated);
        Assert.Contains("AddGeneratedConsumers", generated);
        Assert.Contains("global::MyApp.OrderPlacedConsumer", generated);
        Assert.Contains("global::MyApp.OrderPlaced", generated);
        Assert.Contains("builder.AddConsumer<global::MyApp.OrderPlacedConsumer, global::MyApp.OrderPlaced>()", generated);
    }

    [Fact]
    public void Generator_MultipleConsumers_SameMessageType_GeneratesAllRegistrations()
    {
        const string source = """
            using System.Threading;
            using System.Threading.Tasks;
            using InterBus;

            namespace MyApp
            {
                public record OrderPlaced(System.Guid OrderId);

                public sealed class OrderPlacedConsumer : IConsumer<OrderPlaced>
                {
                    public Task Consume(OrderPlaced message, CancellationToken ct = default)
                        => Task.CompletedTask;
                }

                public sealed class AuditConsumer : IConsumer<OrderPlaced>
                {
                    public Task Consume(OrderPlaced message, CancellationToken ct = default)
                        => Task.CompletedTask;
                }
            }
            """;

        var result = RunGenerator(source);

        Assert.Empty(result.Diagnostics);
        Assert.Single(result.GeneratedTrees);

        var generated = result.GeneratedTrees[0].ToString();
        Assert.Contains("global::MyApp.OrderPlacedConsumer", generated);
        Assert.Contains("global::MyApp.AuditConsumer", generated);
    }

    [Fact]
    public void Generator_ConsumerImplementsMultipleMessageTypes_GeneratesOneLinePerPair()
    {
        const string source = """
            using System.Threading;
            using System.Threading.Tasks;
            using InterBus;

            namespace MyApp
            {
                public record OrderPlaced(System.Guid OrderId);
                public record OrderShipped(System.Guid OrderId);

                /// <summary>A single class handling two message types.</summary>
                public sealed class MultiConsumer : IConsumer<OrderPlaced>, IConsumer<OrderShipped>
                {
                    public Task Consume(OrderPlaced message, CancellationToken ct = default)
                        => Task.CompletedTask;
                    public Task Consume(OrderShipped message, CancellationToken ct = default)
                        => Task.CompletedTask;
                }
            }
            """;

        var result = RunGenerator(source);

        Assert.Empty(result.Diagnostics);
        Assert.Single(result.GeneratedTrees);

        var generated = result.GeneratedTrees[0].ToString();

        // One line for each interface.
        Assert.Contains(
            "builder.AddConsumer<global::MyApp.MultiConsumer, global::MyApp.OrderPlaced>()",
            generated);
        Assert.Contains(
            "builder.AddConsumer<global::MyApp.MultiConsumer, global::MyApp.OrderShipped>()",
            generated);
    }

    // -------------------------------------------------------------------------
    // Abstract / non-concrete classes are skipped
    // -------------------------------------------------------------------------

    [Fact]
    public void Generator_AbstractConsumer_IsNotRegistered()
    {
        const string source = """
            using System.Threading;
            using System.Threading.Tasks;
            using InterBus;

            namespace MyApp
            {
                public record OrderPlaced(System.Guid OrderId);

                // Abstract — must be skipped even though it implements IConsumer<T>.
                public abstract class BaseConsumer : IConsumer<OrderPlaced>
                {
                    public abstract Task Consume(OrderPlaced message, CancellationToken ct = default);
                }

                public sealed class ConcreteConsumer : BaseConsumer
                {
                    public override Task Consume(OrderPlaced message, CancellationToken ct = default)
                        => Task.CompletedTask;
                }
            }
            """;

        var result = RunGenerator(source);

        Assert.Single(result.GeneratedTrees); // ConcreteConsumer only
        var generated = result.GeneratedTrees[0].ToString();

        Assert.Contains("global::MyApp.ConcreteConsumer", generated);
        Assert.DoesNotContain("global::MyApp.BaseConsumer", generated);
    }

    // -------------------------------------------------------------------------
    // No consumers → no output
    // -------------------------------------------------------------------------

    [Fact]
    public void Generator_NoConsumersInAssembly_ProducesNoOutput()
    {
        const string source = """
            namespace MyApp
            {
                public class NotAConsumer { }
            }
            """;

        var result = RunGenerator(source);

        Assert.Empty(result.GeneratedTrees);
    }

    [Fact]
    public void Generator_InterBusNotReferenced_ProducesNoOutput()
    {
        // Build a compilation that does NOT reference InterBus at all.
        const string source = """
            namespace MyApp
            {
                public interface IConsumer<T> { } // local, not InterBus
                public class Foo : IConsumer<int> { }
            }
            """;

        var compilation = CSharpCompilation.Create(
            "TestAssembly",
            [CSharpSyntaxTree.ParseText(source)],
            [MetadataReference.CreateFromFile(typeof(object).Assembly.Location)],
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

        var driver = CSharpGeneratorDriver
            .Create(new ConsumerRegistrationGenerator())
            .RunGeneratorsAndUpdateCompilation(compilation, out _, out _);

        Assert.Empty(driver.GetRunResult().GeneratedTrees);
    }

    // -------------------------------------------------------------------------
    // Generated code structure
    // -------------------------------------------------------------------------

    [Fact]
    public void Generator_GeneratedFile_UsesFullyQualifiedNames()
    {
        const string source = """
            using System.Threading;
            using System.Threading.Tasks;
            using InterBus;

            namespace Deep.Nested.Namespace
            {
                public record MyMessage(string Text);

                public sealed class MyConsumer : IConsumer<MyMessage>
                {
                    public Task Consume(MyMessage message, CancellationToken ct = default)
                        => Task.CompletedTask;
                }
            }
            """;

        var result = RunGenerator(source);

        Assert.Single(result.GeneratedTrees);
        var generated = result.GeneratedTrees[0].ToString();

        // Names must be fully qualified so no using directives are required in the generated file.
        Assert.Contains("global::Deep.Nested.Namespace.MyConsumer", generated);
        Assert.Contains("global::Deep.Nested.Namespace.MyMessage", generated);
        Assert.Contains("global::InterBus.IInterBusBuilder", generated);
    }

    [Fact]
    public void Generator_GeneratedFile_IsInInterBusGeneratedNamespace()
    {
        const string source = """
            using System.Threading;
            using System.Threading.Tasks;
            using InterBus;

            namespace MyApp
            {
                public record Ping;

                public sealed class PingConsumer : IConsumer<Ping>
                {
                    public Task Consume(Ping message, CancellationToken ct = default)
                        => Task.CompletedTask;
                }
            }
            """;

        var result = RunGenerator(source);
        var generated = result.GeneratedTrees[0].ToString();

        Assert.Contains("namespace InterBus.Generated", generated);
        Assert.Contains("internal static class InterBusConsumerRegistrations", generated);
    }

    // -------------------------------------------------------------------------
    // Helpers
    // -------------------------------------------------------------------------

    private static GeneratorDriverRunResult RunGenerator(string source)
    {
        var compilation = CreateCompilationWithInterBus(source);
        var driver = CSharpGeneratorDriver
            .Create(new ConsumerRegistrationGenerator())
            .RunGeneratorsAndUpdateCompilation(compilation, out _, out _);
        return driver.GetRunResult();
    }

    /// <summary>
    /// Creates a minimal <see cref="CSharpCompilation"/> that includes the InterBus assembly
    /// so that <c>InterBus.IConsumer&lt;T&gt;</c> can be resolved by the generator.
    /// </summary>
    private static CSharpCompilation CreateCompilationWithInterBus(string source)
    {
        var dotnetDir = Path.GetDirectoryName(typeof(object).Assembly.Location)!;

        var references = new List<MetadataReference>
        {
            // Core BCL.
            MetadataReference.CreateFromFile(typeof(object).Assembly.Location),
            // InterBus: provides IConsumer<T> and IInterBusBuilder.
            MetadataReference.CreateFromFile(typeof(IConsumer).Assembly.Location),
        };

        // Add additional framework reference assemblies that may be needed by user source.
        foreach (var name in new[] { "System.Runtime.dll", "System.Collections.dll", "netstandard.dll" })
        {
            var path = Path.Combine(dotnetDir, name);
            if (File.Exists(path))
                references.Add(MetadataReference.CreateFromFile(path));
        }

        return CSharpCompilation.Create(
            "TestAssembly",
            [CSharpSyntaxTree.ParseText(source)],
            references,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
    }
}

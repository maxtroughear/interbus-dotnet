    [Fact]
    public void Generator_GeneratedDispatch_ContainsMessageTypeHeaderCheck()
    {
        const string source = """
                              using System.Threading;
                              using System.Threading.Tasks;
                              using InterBus;

                              namespace MyApp
                              {
                                  public record OrderPlaced(System.Guid OrderId);
                                  public record OrderShipped(System.Guid OrderId);

                                  public sealed class MultiConsumer : IConsumer<OrderPlaced>, IConsumer<OrderShipped>
                                  {
                                      public Task Consume(OrderPlaced m, IConsumeContext ctx, CancellationToken ct = default) => Task.CompletedTask;
                                      public Task Consume(OrderShipped m, IConsumeContext ctx, CancellationToken ct = default) => Task.CompletedTask;
                                  }
                              }
                              """;

        var result = RunGenerator(source);
        var generated = result.GeneratedTrees[0].ToString();

        // Dispatch reads the message type header, not the topic name.
        Assert.Contains("InterBusHeaders.MessageType", generated);
        // Dispatch branches on the fully-qualified message type name (matching typeof(T).FullName).
        Assert.Contains("\"MyApp.OrderPlaced\"", generated);
        Assert.Contains("\"MyApp.OrderShipped\"", generated);
        // Passes the IConsumeContext directly to the consumer; no separate context factory call.
        Assert.Contains("context.Headers", generated);
        Assert.DoesNotContain("ConsumeContextFactory", generated);
        // Falls through to error log for unknown types.
        Assert.Contains("does not handle message type", generated);
    }

    // -------------------------------------------------------------------------
    // Helpers
    // -------------------------------------------------------------------------

    private static GeneratorDriverRunResult RunGenerator(string source)
    {
        var compilation = CreateCompilationWithInterBus(source);
        var driver = CSharpGeneratorDriver
            .Create(new ConsumerRegistrationGenerator())
            .RunGeneratorsAndUpdateCompilation(compilation, out _, out _);
        return driver.GetRunResult();
    }

    /// <summary>
    /// Creates a minimal <see cref="CSharpCompilation"/> that includes the InterBus assembly
    /// so that <c>InterBus.IConsumer&lt;T&gt;</c> can be resolved by the generator.
    /// </summary>
    private static CSharpCompilation CreateCompilationWithInterBus(string source)
    {
        var dotnetDir = Path.GetDirectoryName(typeof(object).Assembly.Location)!;

        var references = new List<MetadataReference>
        {
            // Core BCL.
            MetadataReference.CreateFromFile(typeof(object).Assembly.Location),
            // InterBus: provides IConsumer<T> and IInterBusBuilder.
            MetadataReference.CreateFromFile(typeof(IConsumer).Assembly.Location),
        };

        // Add additional framework reference assemblies that may be needed by user source.
        foreach (var name in new[] { "System.Runtime.dll", "System.Collections.dll", "netstandard.dll" })
        {
            var path = Path.Combine(dotnetDir, name);
            if (File.Exists(path))
                references.Add(MetadataReference.CreateFromFile(path));
        }

        return CSharpCompilation.Create(
            "TestAssembly",
            [CSharpSyntaxTree.ParseText(source)],
            references,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
    }
